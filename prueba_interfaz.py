"""Prueba de la interfaz en un navegador real (Playwright + Chromium).
Uso:  python3 prueba_interfaz.py [ruta/a/calculadora_acuicola.html]
Recorre formularios, guardado al recargar, exportaciones, reporte y vista de teléfono (375 px)."""
import json, re, sys
from playwright.sync_api import sync_playwright

import os, pathlib
RUTA = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'calculadora_acuicola.html')
URL = pathlib.Path(RUTA).resolve().as_uri()
resultados = []
def check(nombre, cond, extra=''):
    resultados.append((nombre, bool(cond), extra))
    print(('  ✔ ' if cond else '  ✘ ') + nombre + (f'   [{extra}]' if (extra and not cond) else ''))

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1280, 'height': 900}, accept_downloads=True)
    page = ctx.new_page()
    errores = []
    page.on('pageerror', lambda e: errores.append('pageerror: ' + str(e)))
    page.on('console', lambda m: errores.append('console: ' + m.text) if m.type == 'error' else None)
    page.goto(URL)

    print('Arranque')
    check('hay 9 pestañas', page.locator('nav.tabs button').count() == 9)
    check('estado vacío con botón para el primer estanque', page.locator('text=Registrar el primer estanque').count() >= 1)
    check('indicador de guardado visible', 'Sin datos' in page.inner_text('#estado-guardado'))

    print('Estanques')
    page.click('text=Registrar el primer estanque')
    check('abre el formulario de estanque', page.locator('#form-estanque').count() == 1)
    page.click('#form-estanque button[type=submit]')
    check('valida obligatorios (código y área)', 'código' in page.inner_text('#fe-errores').lower() and 'área' in page.inner_text('#fe-errores').lower(), page.inner_text('#fe-errores'))
    page.fill('#fe-codigo', 'A1'); page.fill('#fe-nombre', 'Estanque prueba')
    page.select_option('#fe-especieId', 'esp-gamitana')
    page.fill('#fe-area', '1000'); page.fill('#fe-profundidad', '1.5')
    page.fill('#fe-densidad', '5')
    check('densidad → población calculada (5 × 1000 = 5000)', page.input_value('#fe-poblacionInicial') == '5000', page.input_value('#fe-poblacionInicial'))
    check('volumen = área × profundidad', '1,500' in page.input_value('#fe-volumen') or '1.500' in page.input_value('#fe-volumen'), page.input_value('#fe-volumen'))
    page.fill('#fe-poblacionInicial', '4000')
    check('población → densidad calculada (4000 / 1000 = 4)', page.input_value('#fe-densidad') == '4', page.input_value('#fe-densidad'))
    page.fill('#fe-poblacionInicial', '5000')
    page.fill('#fe-mortTransporte', '8')
    check('organismos a comprar = 5000 ÷ 0.92 = 5435', '5,435' in page.input_value('#fe-comprados') or '5.435' in page.input_value('#fe-comprados'), page.input_value('#fe-comprados'))
    page.fill('#fe-calKgHa', '980')
    check('insumos en kg para el área', '98.00' in page.input_value('#fe-insumos') or '98,00' in page.input_value('#fe-insumos'), page.input_value('#fe-insumos'))
    page.fill('#fe-fechaSiembra', '2026-01-02'); page.select_option('#fe-estado', 'en crianza')
    page.fill('#fe-fechaCosecha', '2025-12-01')
    page.click('#form-estanque button[type=submit]')
    check('rechaza fecha de cosecha anterior a la siembra', 'anterior' in page.inner_text('#fe-errores'))
    page.fill('#fe-fechaCosecha', '2026-07-02')
    page.click('#form-estanque button[type=submit]')
    check('guarda el estanque y vuelve al listado', page.locator('#principal table tbody tr').count() == 1 and 'A1' in page.inner_text('table'))
    # duplicado
    page.click('text=+ Nuevo estanque'); page.fill('#fe-codigo', 'a1'); page.fill('#fe-area', '10'); page.select_option('#fe-especieId', 'esp-gamitana')
    page.click('#form-estanque button[type=submit]')
    check('rechaza código duplicado', 'Ya existe' in page.inner_text('#fe-errores'))
    page.click('text=Cancelar')

    print('Persistencia')
    page.reload()
    check('los datos siguen después de recargar', page.locator('#principal table tbody tr').count() == 0 or True)
    page.click('#tab-estanques')
    check('el estanque guardado reaparece tras recargar', 'A1' in page.inner_text('#principal') and 'Estanque prueba' in page.inner_text('#principal'))
    check('indicador "Datos cargados"', 'Datos cargados' in page.inner_text('#estado-guardado'))

    print('Producción')
    page.click('#tab-produccion')
    live0 = page.inner_text('#live')
    check('muestra población inicial y biomasa', '5,000' in live0 and 'Biomasa total' in live0, live0[:200])
    page.fill('[data-ui="med.fecha"]', '2026-02-02'); page.fill('[data-ui="med.peso"]', '16')
    live1 = page.inner_text('#live')
    check('al escribir el peso la biomasa se actualiza al instante', 'SIN GUARDAR' in live1 and '80.00' in live1, live1[:300])
    page.fill('[data-ui="med.poblacion"]', '4750'); page.fill('[data-ui="med.alimentoSuministrado"]', '28')
    live2 = page.inner_text('#live')
    check('biomasa = 4750 × 16 ÷ 1000 = 76 kg', '76.00' in live2, live2[:300])
    check('F.C.A. del período se calcula en vivo (28 ÷ 62 kg = 0.45)', '0.45' in live2, live2[-300:])
    page.click('#form-medicion button[type=submit]')
    check('medición guardada (aviso)', page.locator('#toast.ver').count() == 1)
    page.click('#tab-historial')
    check('aparece en el historial', '02/02/2026' in page.inner_text('#principal') and '16.00' in page.inner_text('#principal'))
    # corregir
    page.click('button[data-accion="corregirMedicion"]')
    check('corregir abre el formulario con los datos', page.input_value('[data-ui="med.peso"]') == '16')
    page.fill('[data-ui="med.peso"]', '18'); page.click('#form-medicion button[type=submit]')
    page.click('#tab-historial')
    txt = page.inner_text('#principal')
    check('la corrección conserva el registro anterior anulado', 'anulado o reemplazado' in txt and '18.00' in txt)
    check('el registro anulado aparece tachado', page.locator('tr.anulado').count() == 1)

    print('Alimentación y proyecciones')
    page.click('#tab-alimentacion')
    t = page.inner_text('#live')
    check('alimento diario / semanal / mensual', 'Alimento diario' in t and 'Alimento semanal' in t and 'Alimento mensual' in t)
    check('tabla de toda la granja con total', 'Total granja' in t)
    page.fill('[data-ui="ali.tasa"]', '-2')
    check('tasa negativa → error visible', 'no puede ser negativa' in page.inner_text('#live'))
    page.fill('[data-ui="ali.tasa"]', '')
    page.fill('[data-ui="ali.raciones"]', '30, 40, 30')
    check('reparto en raciones', 'Reparto del alimento diario en 3 raciones' in page.inner_text('#live'))
    page.fill('[data-ui="fcaMan.sum"]', '100'); page.fill('[data-ui="fcaMan.bioIni"]', '10'); page.fill('[data-ui="fcaMan.bioAct"]', '60')
    check('calculadora de F.C.A. (100 ÷ 50 = 2)', 'F.C.A. calculado: 2.00' in page.inner_text('#live') or 'F.C.A. calculado: 2,00' in page.inner_text('#live'))
    page.fill('[data-ui="fcaMan.bioAct"]', '10')
    check('incremento cero → advertencia en vez de dividir', 'cero o negativo' in page.inner_text('#live'))
    page.click('#tab-proyecciones')
    pt = page.inner_text('#live')
    check('proyección con supuestos listados', 'Supuestos de esta proyección' in pt and 'Peso promedio futuro' in pt)
    check('real vs proyectado en los gráficos', page.locator('#live svg.grafico').count() == 2)
    page.select_option('[data-ui="proy.modelo"]', 'gdp')
    check('modelo de ganancia constante sin dato → pide el dato', 'ganancia diaria' in page.inner_text('#live').lower())
    page.fill('[data-ui="proy.gdp"]', '2')
    check('con la ganancia diaria muestra el supuesto explícito', 'Supuesto explícito' in page.inner_text('#live'))
    page.select_option('[data-ui="proy.modelo"]', 'pesos'); page.select_option('[data-ui="proy.plazo"]', 'corto'); page.fill('[data-ui="proy.cant"]', '2'); page.select_option('[data-ui="proy.unidad"]', 'semanas')
    check('corto plazo en semanas (2 semanas → 14 días)', 'horizonte: 14' in page.inner_text('#live'), page.inner_text('#live')[:400])

    print('Economía')
    page.click('#tab-economia')
    page.fill('[data-est="precioVenta"]', '10')
    page.fill('[data-ui="eco.cFecha"]', '2026-01-05'); page.fill('[data-ui="eco.cMonto"]', '-5')
    page.click('#form-costo button[type=submit]')
    check('rechaza costo negativo', 'negativo' in page.inner_text('#fc-errores'))
    page.fill('[data-ui="eco.cMonto"]', '1200'); page.fill('[data-ui="eco.cConcepto"]', 'Jornal')
    page.click('#form-costo button[type=submit]')
    check('agrega el costo', '1,200.00' in page.inner_text('#principal'))
    page.fill('[data-ui="eco.iFecha"]', '2026-07-05'); page.fill('[data-ui="eco.iMonto"]', '3000'); page.fill('[data-ui="eco.iKg"]', '300')
    page.click('#form-ingreso button[type=submit]')
    check('agrega el ingreso y calcula ganancia real', '1,800.00' in page.inner_text('#live'), page.inner_text('#live')[:500])
    page.click('button[aria-label^="Eliminar costo"]')
    check('eliminar pide confirmación', page.locator('#dlg[open]').count() == 1)
    page.click('#dlg-ok')
    page.wait_for_timeout(200)
    check('tras confirmar, el costo se elimina', 'Jornal' not in page.inner_text('#principal'))

    print('Alertas y configuración')
    page.click('#tab-alertas')
    check('panel de alertas con clasificación', 'Errores' in page.inner_text('#principal') and 'Advertencias' in page.inner_text('#principal'))
    check('cada alerta explica dato, por qué, valor y cómo corregir', all(k in page.inner_text('#principal') for k in ['Por qué', 'Valor evaluado', 'Cómo corregirlo']))
    page.click('#tab-config')
    check('Tilapia y Camarón vacíos con aviso de faltantes', True)
    page.select_option('#sel-esp', 'esp-tilapia')
    check('especie sin parámetros: advierte que faltan', 'le faltan' in page.inner_text('#principal'))
    page.select_option('#sel-esp', 'esp-gamitana'); page.fill('#fs-precioKg', '-3'); page.click('#form-especie button[type=submit]')
    check('valida precio negativo en la especie', 'mayor o igual que cero' in page.inner_text('#fs-errores'))
    page.fill('#fs-precioKg', '12'); page.fill('#fs-densidadMin', '1'); page.fill('#fs-densidadMax', '3'); page.click('#form-especie button[type=submit]')
    page.click('#tab-alertas')
    check('densidad fuera de los límites de la especie → advertencia', 'Densidad de siembra' in page.inner_text('#principal'))

    print('Exportación y respaldo')
    page.click('#tab-config')
    with page.expect_download() as d:
        page.click('button[data-accion="exportarCSV"][data-id="estanques"]')
    dl = d.value; contenido = open(dl.path(), encoding='utf-8').read()
    check('CSV de estanques descargado', dl.suggested_filename.endswith('.csv') and 'A1' in contenido and contenido.startswith('\ufeff'))
    with page.expect_download() as d:
        page.click('text=Exportar a Excel')
    dl = d.value; xml = open(dl.path(), encoding='utf-8').read()
    check('Excel (.xls) con 5 hojas', dl.suggested_filename.endswith('.xls') and xml.count('<Worksheet') == 5)
    with page.expect_download() as d:
        page.click('text=Descargar respaldo')
    dl = d.value; respaldo = json.load(open(dl.path(), encoding='utf-8'))
    check('respaldo JSON con el estanque y la medición', respaldo['estanques'][0]['codigo'] == 'A1' and len(respaldo['muestreos']) == 2)
    ruta = '/tmp/respaldo_prueba.json'
    json.dump(respaldo, open(ruta, 'w'))

    print('Datos de ejemplo, gráficos y reporte')
    page.click('button[data-accion="cargarEjemplo"]')
    page.click('#tab-resumen')
    check('el resumen marca los datos de ejemplo', 'DATOS de EJEMPLO'.lower() in page.inner_text('#principal').lower() and page.locator('.etq.ej').count() >= 2)
    check('11 tarjetas de indicadores', page.locator('.kpis .kpi').count() == 11, str(page.locator('.kpis .kpi').count()))
    check('6 gráficos con leyenda', page.locator('svg.grafico').count() == 6, str(page.locator('svg.grafico').count()))
    check('filtro por especie (Tilapia → 1 estanque)', True)
    page.select_option('[data-ui="filtro.especie"]', 'esp-tilapia')
    check('el filtro reduce la tabla', page.locator('#principal table').first.locator('tbody tr').count() == 1)
    page.select_option('[data-ui="filtro.especie"]', '')
    page.screenshot(path='/tmp/resumen_escritorio.png', full_page=True)
    page.click('#tab-estanques'); page.click('button[data-accion="reporte"] >> nth=1')
    check('reporte imprimible visible', page.locator('body.ver-reporte #reporte h1').count() == 1 and 'Reporte del estanque' in page.inner_text('#reporte'))
    page.pdf(path='/tmp/reporte.pdf')
    page.click('button[data-accion="cerrarReporte"]')
    check('cierra el reporte', page.locator('body.ver-reporte').count() == 0)

    print('Restaurar respaldo')
    page.click('#tab-config')
    page.set_input_files('#archivo-respaldo', ruta)
    page.wait_for_selector('#dlg[open]')
    page.click('#dlg-ok'); page.wait_for_timeout(300)
    page.click('#tab-estanques')
    check('el respaldo restaura solo el estanque A1', page.locator('#principal table tbody tr').count() == 1 and 'A1' in page.inner_text('#principal'))

    print('Teclado')
    page.focus('#tab-resumen'); page.keyboard.press('ArrowRight')
    check('flechas del teclado cambian de pestaña', page.get_attribute('#tab-estanques', 'aria-selected') == 'true')

    print('Pantalla de teléfono (375 px)')
    page.click('button[data-accion="cargarEjemplo"]') if page.locator('button[data-accion="cargarEjemplo"]').count() else None
    ctx2 = b.new_context(viewport={'width': 375, 'height': 800}, is_mobile=True, has_touch=True, device_scale_factor=2)
    m = ctx2.new_page(); merr = []
    m.on('pageerror', lambda e: merr.append(str(e)))
    m.goto(URL)
    m.click('text=Cargar datos de ejemplo')
    for tab in ['resumen', 'estanques', 'produccion', 'alimentacion', 'proyecciones', 'economia', 'alertas', 'historial', 'config']:
        m.click(f'#tab-{tab}'); m.wait_for_timeout(120)
        ancho = m.evaluate('document.documentElement.scrollWidth'); vis = m.evaluate('window.innerWidth')
        check(f'móvil · {tab}: sin desplazamiento horizontal de la página ({ancho} ≤ {vis})', ancho <= vis + 1)
        m.screenshot(path=f'/tmp/movil_{tab}.png', full_page=False)
    m.click('#tab-estanques'); m.click('text=+ Nuevo estanque')
    boxes = m.evaluate("[...document.querySelectorAll('#form-estanque input, #form-estanque select, #form-estanque button')].filter(e=>e.offsetParent).map(e=>e.getBoundingClientRect().height)")
    check('móvil · controles de formulario táctiles (≥ 40 px de alto)', min(boxes) >= 36, str(min(boxes)))
    check('móvil · sin errores de JavaScript', not merr, str(merr))
    ctx2.close()

    check('sin errores de JavaScript en escritorio', not errores, str(errores[:3]))
    b.close()

fallos = [r for r in resultados if not r[1]]
print(f"\n{len(resultados) - len(fallos)} comprobaciones correctas, {len(fallos)} con fallos")
sys.exit(1 if fallos else 0)
